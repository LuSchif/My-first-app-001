// Writes dist/sw.js, the service worker that lets Broomit start without a network connection.
// It precaches every file of the app build under a cache named after the build's content, so
// a new deploy gets a new cache and old ones are removed once it takes over.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const DIST = 'dist'
// Spikes and deploy metadata are not part of the app.
const SKIP = new Set(['sw.js', 'version.json', 'ink-test.html'])

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? walk(path) : [path]
  })
}

const files = walk(DIST)
  .map((path) => relative(DIST, path).split('\\').join('/'))
  .filter((path) => !SKIP.has(path) && !path.endsWith('.map'))
  .sort()

const hash = createHash('sha256')
for (const file of files) hash.update(file).update(readFileSync(join(DIST, file)))
const version = hash.digest('hex').slice(0, 12)

const worker = `// Generated by scripts/build-service-worker.mjs
const CACHE = 'broomit-${version}'
const FILES = ${JSON.stringify(['./', ...files], null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES))
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith('broomit-') && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return
  if (request.mode === 'navigate') {
    // Pages: the newest version when online, the cached app when offline. The browser's HTTP
    // cache may keep the page for minutes (GitHub Pages allows 10), so it is always revalidated.
    event.respondWith(
      fetch(request.url, { cache: 'no-cache', credentials: 'same-origin' })
        .then((response) => {
          if (response.ok) {
            const copy = response.clone()
            void caches.open(CACHE).then((cache) => cache.put(request, copy))
          }
          return response
        })
        .catch(() =>
          caches.match(request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || caches.match('./', { ignoreVary: true })),
        ),
    )
    return
  }
  // Build files have content hashes in their names, so a cached copy never goes stale.
  event.respondWith(
    caches.match(request, { ignoreVary: true }).then((hit) => hit || fetch(request)),
  )
})
`

writeFileSync(join(DIST, 'sw.js'), worker)
console.log(`service worker: ${files.length} files, cache broomit-${version}`)
