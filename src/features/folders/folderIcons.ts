const BY_NAME = new globalThis.Map<string, LucideIcon>(FOLDER_ICON_GROUPS.flatMap((g) => g.icons))

export const DEFAULT_FOLDER_ICON = 'Folder'

/** The icon for a stored name; unknown names (from a newer version) show a plain folder. */
export function folderIcon(name: string): LucideIcon {
  return BY_NAME.get(name) ?? Folder
}
